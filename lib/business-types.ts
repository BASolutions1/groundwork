/** Types whose name starts with what the person has typed. */
export function businessTypesStartingWith(query: string): string[] {
  const prefix = query.trim().toLowerCase();
  if (!prefix) return [];
  return BUSINESS_TYPES.filter((type) => type.toLowerCase().startsWith(prefix));
}
