const SMALL_WORDS = new Set(["a", "an", "and", "of", "or", "the"]);

/**
 * Suggestions for what the person has typed.
 * Names that start with the text come first. A later word can match once they have typed two letters,
 * so "salon" offers Hair salon and Nail salon.
 */
export function businessTypesStartingWith(query: string): string[] {
  const prefix = query.trim().toLowerCase();
  if (!prefix) return [];

  const leading: string[] = [];
  const later: string[] = [];

  for (const type of BUSINESS_TYPES) {
    const lower = type.toLowerCase();
    if (lower.startsWith(prefix)) {
      leading.push(type);
      continue;
    }
    if (prefix.length < 2) continue;
    const words = lower.split(/[^a-z0-9]+/).filter((word) => word && !SMALL_WORDS.has(word));
    if (words.slice(1).some((word) => word.startsWith(prefix))) later.push(type);
  }

  return [...leading, ...later];
}
